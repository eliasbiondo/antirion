// Generates the typed Admin API client inputs from the contract in openapi/admin-api.yaml:
//   src/lib/api/schema.d.ts      paths, operations and schemas (openapi-typescript)
//   src/lib/api/operations.ts    every operation's method, path and permission
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { parse } from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contract = resolve(root, process.env.ANTIRION_ADMIN_API ?? '../openapi/admin-api.yaml');
const bin = (name) => resolve(root, 'node_modules/.bin', name);

execFileSync(
  bin('openapi-typescript'),
  [
    contract,
    '-o',
    'src/lib/api/schema.d.ts',
    '--root-types',
    '--empty-objects-unknown',
    '--default-non-nullable=false',
  ],
  {
    cwd: root,
    stdio: 'inherit',
  },
);

// The generated types keep only the declarations, not the contract's descriptions.
const schemaFile = resolve(root, 'src/lib/api/schema.d.ts');
const generated = readFileSync(schemaFile, 'utf8').replace(/^\s*\/\*\*[\s\S]*?\*\/\n/gm, '');
writeFileSync(
  schemaFile,
  `// Generated by scripts/generate-api.mjs from the Admin API contract; do not edit.\n${generated}`,
);

const doc = parse(readFileSync(contract, 'utf8'));
const methods = ['get', 'put', 'post', 'patch', 'delete'];
const rows = [];
for (const [path, item] of Object.entries(doc.paths)) {
  for (const method of methods) {
    const op = item[method];
    if (!op?.operationId) continue;
    // A create-or-replace PUT names two permissions; the console only replaces with PUT.
    const declared = op['x-antirion-permission'] ?? 'authenticated';
    const upsert = /^(\S+) \(create\) \/ (\S+) \(replace\)$/.exec(declared);
    rows.push({
      id: op.operationId,
      method,
      path,
      permission: upsert ? upsert[2] : declared,
    });
  }
}
rows.sort((a, b) => a.id.localeCompare(b.id));

const body = rows
  .map((r) => `  ${r.id}: { method: '${r.method}', path: '${r.path}', permission: '${r.permission}' },`)
  .join('\n');

writeFileSync(
  resolve(root, 'src/lib/api/operations.ts'),
  `// Generated by scripts/generate-api.mjs from the Admin API contract; do not edit.

export interface OperationInfo {
  method: 'get' | 'put' | 'post' | 'patch' | 'delete';
  path: string;
  /** The permission the operation needs, or \`public\` / \`authenticated\`. */
  permission: string;
}

export const OPERATIONS = {
${body}
} as const satisfies Record<string, OperationInfo>;

export type OperationId = keyof typeof OPERATIONS;
`,
);

execFileSync(bin('prettier'), ['--write', 'src/lib/api/operations.ts'], {
  cwd: root,
  stdio: 'inherit',
});
